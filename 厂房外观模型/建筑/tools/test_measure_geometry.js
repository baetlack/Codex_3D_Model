'use strict';
require('../building_measure.js');
const assert=require('node:assert/strict');
const {metrics,rayTriangle,rayBox}=globalThis.BuildingMeasure.geometry;
const triangle={a:[0,0,0],e1:[650,0,0],e2:[0,650,0]};
assert.equal(rayTriangle({origin:[100,100,1000],direction:[0,0,-1],maxDistance:2000},triangle),1000);
assert.equal(rayTriangle({origin:[100,100,-1000],direction:[0,0,1],maxDistance:2000},triangle),1000);
assert.equal(rayTriangle({origin:[600,600,1000],direction:[0,0,-1],maxDistance:2000},triangle),null);
assert.equal(rayTriangle({origin:[100,100,1000],direction:[1,0,0],maxDistance:2000},triangle),null);
assert.equal(rayTriangle({origin:[100,100,1000],direction:[0,0,-1],maxDistance:900},triangle),null);
assert.equal(rayBox({origin:[325,-1000,1000],direction:[0,1,0],maxDistance:3000},[0,0,0],[650,650,23000]),true);
assert.equal(rayBox({origin:[651,-1000,1000],direction:[0,1,0],maxDistance:3000},[0,0,0],[650,650,23000]),false);
assert.equal(rayBox({origin:[325,-1000,1000],direction:[0,-1,0],maxDistance:3000},[0,0,0],[650,650,23000]),false);
assert.equal(metrics([0,0,0],[650,0,0]).value,650);
assert.equal(metrics([0,0,0],[3000,4000,12000]).value,13000);
assert.equal(metrics([0,0,0],[3000,4000,12000],'axis').value,5000);
assert.equal(metrics([0,0,6000],[1000,2000,0],'height').value,6000);
assert.deepEqual(metrics([0,0,6000],[1000,2000,0]).delta,[1000,2000,-6000]);
